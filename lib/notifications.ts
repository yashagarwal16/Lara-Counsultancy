export async function sendEnquiryEmail(enquiry: EnquiryNotification) {
  const recipients = [1, 2, 3, 4]
    .map((index) => process.env[`CONTACT_RECIPIENT_${index}`])
    .filter((value): value is string => Boolean(value));
  if (!recipients.length) throw new Error("At least one CONTACT_RECIPIENT_n is required.");

  const transporter = nodemailer.createTransport({
    host: required("SMTP_HOST"),
    port: Number(process.env.SMTP_PORT || 587),
    secure: process.env.SMTP_SECURE === "true",
    auth: { user: required("SMTP_USER"), pass: required("SMTP_PASSWORD") },
  });
  const from = required("MAIL_FROM");
  await transporter.sendMail({
    from,
    to: recipients,
    replyTo: enquiry.email,
    subject: `[${siteName}] New ${enquiry.type} enquiry`,
    text: formatMessage(enquiry),
    html: formatHtml(enquiry),
  });
}

export async function sendEnquiryWhatsApp(enquiry: EnquiryNotification) {
  const sid = required("TWILIO_ACCOUNT_SID");
  const token = required("TWILIO_AUTH_TOKEN");
  const from = required("TWILIO_WHATSAPP_FROM");
  const to = required("TWILIO_WHATSAPP_TO");
  const body = new URLSearchParams({ From: `whatsapp:${from}`, To: `whatsapp:${to}`, Body: formatMessage(enquiry) });
  const response = await fetch(`https://api.twilio.com/2010-04-01/Accounts/${sid}/Messages.json`, {
    method: "POST",
    headers: { Authorization: `Basic ${Buffer.from(`${sid}:${token}`).toString("base64")}`, "Content-Type": "application/x-www-form-urlencoded" },
    body,
  });
  if (!response.ok) throw new Error(`Twilio notification failed with status ${response.status}.`);
}
